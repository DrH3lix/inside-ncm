"""Sudoku code swap: do NCM's coarse levels carry commitments the later levels depend on? (DJ + Claude, 2026-10-21.)

Tests the NCM blog's hypothesis that coarse-to-fine generation "supports global planning by establishing an overall
structure before resolving finer details". For puzzle A, the codes of levels 1..k are forced to be the ones the model
generated for a different puzzle B (the donor); levels k+1..12 are generated by the model, still prompted with A.
Controls: A's own codes (must reproduce the baseline) and uniformly random codes. Predictions: HYPOTHESES.md.

  python probe/sudoku_swap.py --task hard --n 1000
"""
import argparse
import json
import os
import pickle
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, HERE)
from drafts import level_snapshots, load  # noqa: E402
from paths import ARTIFACTS, DATA, WORK  # noqa: E402

SEP = 10
KS = [1, 3, 6, 9, 11]


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--task", default="hard")
    ap.add_argument("--n", type=int, default=1000)
    ap.add_argument("--bs", type=int, default=125)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=os.path.join(WORK, "sudoku"))
    a = ap.parse_args()

    ck = os.path.join(ARTIFACTS, "sudoku", a.task)
    cfg, tk, net, _ = load(ck, os.path.join(ck, "config.yaml"))
    vq, dec = tk.vqvae.vq, tk.vqvae.decoder
    levels = list(vq.levels)
    starts = [sum(levels[:i]) for i in range(len(levels))]
    V = [int(v) for v in cfg.model.vocab_size]
    dd = os.path.join(DATA, "sudoku", a.task)
    puzzles = pickle.load(open(os.path.join(dd, "puzzles.pickle"), "rb"))[:a.n]
    S = torch.tensor(pickle.load(open(os.path.join(dd, "solutions.pickle"), "rb"))[:a.n])
    Pz = torch.tensor([p[1:90] for p in puzzles])
    cell = S != SEP
    clue, blank = cell & (Pz != 0), cell & (Pz == 0)

    orig_sample = net._sample_level
    forced = {"codes": None, "k": 0, "i": 0}

    def sample(logits, *args):                                  # level i of this generate() call
        i = forced["i"]
        forced["i"] += 1
        if i < forced["k"]:
            return forced["codes"][:, starts[i]:starts[i] + levels[i]]
        return orig_sample(logits, *args)
    net._sample_level = sample

    def run(codes=None, k=0):
        """Generate all puzzles; codes (N x 322) forced for levels 1..k. Returns final digits N x 89 and all codes."""
        finals, idxs = [], []
        for b in range(0, a.n, a.bs):
            x = torch.tensor(puzzles[b:b + a.bs], device="cuda")
            forced.update(k=k, i=0, codes=None if codes is None else codes[b:b + a.bs].cuda())
            with torch.no_grad():
                idx = net.generate(None, x, temperature=0.0, top_k=0, top_p=1.0)
                full, _ = level_snapshots(vq, idx)
                finals.append(dec(full[-1]).argmax(-1).cpu())
            idxs.append(idx.cpu())
        return torch.cat(finals), torch.cat(idxs)

    def score(final, donor_sol=None):
        r = dict(solved=(final == S).all(-1).float().mean().item(),
                 clue=(final == S)[clue].float().mean().item(),
                 blank=(final == S)[blank].float().mean().item())
        if donor_sol is not None:
            differ = blank & (donor_sol != S)                   # cells where the donor's answer is different
            r["leak"] = ((final == donor_sol) & differ).sum().item() / differ.sum().item()
            r["donor_solved"] = (final == donor_sol).all(-1).float().mean().item()
        return r

    base_final, base_idx = run()
    perm = torch.roll(torch.arange(a.n), 1)                     # puzzle i gets puzzle i-1's codes
    donor_codes, donor_sol = base_idx[perm], S[perm]
    g = torch.Generator().manual_seed(a.seed)
    rand_codes = torch.cat([torch.randint(0, V[i], (a.n, n), generator=g) for i, n in enumerate(levels)], 1)

    out = {"baseline": score(base_final, donor_sol)}
    b = out["baseline"]
    print(f"{a.task}, {a.n} puzzles. baseline: solved {b['solved']:.1%}  clue {b['clue']:.1%}  blank {b['blank']:.1%}  "
          f"(chance-level 'leak' with no swap: {b['leak']:.1%})")
    print("\n  k  codes   | own codes: solved   | DONOR: solved  clue   blank  leak  (solved B's grid) | RANDOM: solved  clue   blank")
    rows = []
    for k in KS:
        nc = starts[k] if k < len(levels) else sum(levels)
        own = score(run(base_idx, k)[0])
        don = score(run(donor_codes, k)[0], donor_sol)
        rnd = score(run(rand_codes, k)[0], donor_sol)
        rows.append(dict(k=k, codes=nc, own=own, donor=don, random=rnd))
        print(f" {k:>2}  {nc:>5}   |        {own['solved']:6.1%}       |  {don['solved']:6.1%} {don['clue']:6.1%} {don['blank']:6.1%} "
              f"{don['leak']:5.1%}   ({don['donor_solved']:5.1%})        |  {rnd['solved']:6.1%} {rnd['clue']:6.1%} {rnd['blank']:6.1%}")
    out["swap"] = rows
    json.dump(out, open(os.path.join(a.out, f"sudoku_swap_{a.task}.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
